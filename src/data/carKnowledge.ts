export const CAR_KNOWLEDGE: CarKnowledge[] = [KIA_RIO_JB, BMW_E90]

export function knowledgeFor(car: Pick<Car, 'make' | 'model' | 'engineCode' | 'vin'> | null | undefined): CarKnowledge | null {
  if (!car) return null
  return CAR_KNOWLEDGE.find((k) => k.match(car)) ?? null
}

/** Подсказка по коду для этой машины: точное совпадение сильнее шаблона `P030*`. */
export function carHint(k: CarKnowledge | null, code: string): string | null {
  if (!k) return null
  const c = code.trim().toUpperCase()
  if (k.hints[c]) return k.hints[c]
  const keys = Object.keys(k.hints).filter((h) => h.endsWith('*') && c.startsWith(h.slice(0, -1)))
  keys.sort((a, b) => b.length - a.length)
  return keys.length ? k.hints[keys[0]] : null
}
